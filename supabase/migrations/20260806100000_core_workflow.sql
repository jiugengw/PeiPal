create table if not exists public.plans (
    id bigint generated by default as identity primary key,
    family_id bigint not null references public.families(id) on delete cascade,
    older_adult_id bigint not null references public.older_adult_profiles(id) on delete cascade,
    activity_id bigint not null references public.activities(id),
    status text not null default 'draft'
        check (status in ('draft', 'awaiting_approval', 'shared', 'cancelled')),
    created_by uuid not null references auth.users(id),
    approved_by uuid references auth.users(id),
    approved_at timestamptz,
    shared_at timestamptz,
    cancelled_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.plan_support_offers (
    id bigint generated by default as identity primary key,
    plan_id bigint not null references public.plans(id) on delete cascade,
    offered_by uuid not null references auth.users(id) on delete cascade,
    support_type text not null
        check (support_type in ('join', 'remind', 'transport', 'alternative', 'booking', 'encourage')),
    note text,
    status text not null default 'offered'
        check (status in ('offered', 'withdrawn')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (plan_id, offered_by, support_type)
);

create index if not exists plans_family_idx on public.plans (family_id);
create index if not exists plans_older_adult_idx on public.plans (older_adult_id);
create index if not exists plans_status_idx on public.plans (status);
create index if not exists plan_support_offers_plan_idx on public.plan_support_offers (plan_id);

alter table public.plans enable row level security;
alter table public.plan_support_offers enable row level security;

drop policy if exists "Family accounts can view plans" on public.plans;
create policy "Family accounts can view plans"
on public.plans for select
to authenticated
using (
    exists (
        select 1
        from public.family_accounts account
        where account.family_id = plans.family_id
          and account.user_id = auth.uid()
    )
);

drop policy if exists "Family accounts can view support offers" on public.plan_support_offers;
create policy "Family accounts can view support offers"
on public.plan_support_offers for select
to authenticated
using (
    exists (
        select 1
        from public.plans plan
        join public.family_accounts account on account.family_id = plan.family_id
        where plan.id = plan_support_offers.plan_id
          and account.user_id = auth.uid()
    )
);
